#!/usr/bin/env python3
"""Summarize station-level *candidate* historical coverage without approving raw QC.

Never impute missing measurements or use 2024/2025 coverage to select training stations.
Input is the versioned coverage_batches.jsonl generated by audit_hourly_coverage.py.
"""
import argparse
import collections
import csv
import hashlib
import json
import pathlib

TRAIN = range(2016, 2024)
VALIDATION = 2024
TEST = 2025
VARIABLES = {
    'temperature': ('TEMP', 'tmpf', 'temperature', 'Temperature'),
    'pressure': ('STATION_PRESSURE', 'mslp', 'alti', 'pressure', 'StationPressure'),
    'humidity': ('RELATIVE_HUMIDITY', 'relh', 'humidity', 'RelativeHumidity'),
    'wind_speed': ('WIND_SPEED', 'sknt', 'wind_speed', 'WindSpeed'),
    'precipitation': ('PRECIP_AMOUNT', 'p01i', 'precipitation', 'Precipitation'),
}

def group_variable(source_name):
    # Exact source names only: arbitrary prefix or suffix matching is unsafe.
    for target, names in VARIABLES.items():
        if source_name in names:
            return target
    return None

def file_sha256(path):
    digest = hashlib.sha256()
    with pathlib.Path(path).open('rb') as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b''):
            digest.update(chunk)
    return digest.hexdigest()

def summarize(manifest, audit, min_years=2, min_fraction=0.5):
    if not (1 <= min_years <= 8 and 0 < min_fraction <= 1):
        raise ValueError('Invalid training coverage thresholds')
    raw_manifest = pathlib.Path(manifest).read_bytes()
    stations = list(csv.DictReader(raw_manifest.decode('utf-8-sig').splitlines()))
    indexed = {(s['provider'], s['station_id']): s for s in stations}
    if len(indexed) != len(stations):
        raise ValueError('Duplicate provider+station IDs in manifest')
    bins = collections.defaultdict(lambda: collections.defaultdict(lambda: collections.defaultdict(lambda: [0, 0])))
    flagged = collections.Counter()
    batch_counts = collections.Counter()
    seen_periods = set()
    skipped = collections.Counter()
    with pathlib.Path(audit).open(encoding='utf-8') as source:
        for line in source:
            if not line.strip():
                continue
            item = json.loads(line)
            key = (item['provider'], item['station_id'])
            if key not in indexed:
                skipped['outside_manifest'] += 1
                continue
            year = int(item['period'][:4])
            if year < 2016 or year > 2025:
                skipped['outside_window'] += 1
                continue
            identity = (key, item['period'])
            if identity in seen_periods:
                raise ValueError('Duplicate provider/station/period in audit: ' + str(identity))
            seen_periods.add(identity)
            batch_counts[key] += 1
            # For each variable/year use summed (period, hour) bins; do not double
            # count overlapping source fields in the same period.
            period_values = collections.defaultdict(list)
            for name, stats in item.get('variables', {}).items():
                target = group_variable(name)
                if not target:
                    continue
                expected = int(item['expected_hours'])
                observed = int(stats.get('observed_hours', 0))
                if not (0 <= observed <= expected):
                    raise ValueError('Invalid hourly coverage: ' + str(key) + ' ' + str(item['period']))
                period_values[target].append(observed)
                if stats.get('source_quality_flags'):
                    flagged[(key, target)] += 1
            for target, values in period_values.items():
                pair = bins[key][year][target]
                pair[0] += max(values)
                pair[1] += int(item['expected_hours'])
    rows = []
    classes = collections.Counter()
    for key, station in sorted(indexed.items()):
        train_years = sorted(year for year in TRAIN if any(
            observed / expected >= min_fraction
            for observed, expected in bins[key][year].values() if expected
        ))
        train_fields = sorted({field for year in TRAIN for field, (observed, expected) in bins[key][year].items()
                               if expected and observed / expected >= min_fraction})
        validation_fields = sorted(field for field, (observed, expected) in bins[key][VALIDATION].items()
                                   if expected and observed > 0)
        test_fields = sorted(field for field, (observed, expected) in bins[key][TEST].items()
                             if expected and observed > 0)
        enough = len(train_years) >= min_years
        klass = 'coverage_candidate_qc_pending' if enough else 'insufficient_training_coverage'
        classes[klass] += 1
        rows.append(dict(provider=key[0], station_id=key[1], country=station.get('country', ''),
                         audited_batches=batch_counts[key], training_year_count=len(train_years),
                         training_years=';'.join(map(str, train_years)),
                         training_variables=';'.join(train_fields),
                         validation_2024_variables=';'.join(validation_fields),
                         evaluation_2025_variables=';'.join(test_fields),
                         flagged_variable_periods=sum(v for (k, _), v in flagged.items() if k == key),
                         readiness=klass, quality_approved='false'))
    report = dict(manifest_sha256=hashlib.sha256(raw_manifest).hexdigest(),
                  coverage_audit_sha256=file_sha256(audit),
                  station_count=len(stations), station_status=dict(classes), skipped_batches=dict(skipped),
                  min_training_years=min_years, min_training_year_coverage_fraction=min_fraction,
                  training_years='2016-2023', validation_year=VALIDATION, evaluation_year=TEST,
                  quality_approved=False,
                  notes=['Coverage candidates only; source flags, units and plausibility are not yet interpreted.',
                         'No 2024/2025 coverage is used to qualify training stations.',
                         'Multiple source fields mapping to one variable are not summed within a period.',
                         'Regional neighbor eligibility and training accuracy have not been tested.'])
    return rows, report

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--manifest', required=True)
    parser.add_argument('--coverage-batches', required=True)
    parser.add_argument('--out', required=True)
    parser.add_argument('--min-years', type=int, default=2)
    parser.add_argument('--min-fraction', type=float, default=0.5)
    args = parser.parse_args()
    rows, report = summarize(args.manifest, args.coverage_batches, args.min_years, args.min_fraction)
    out = pathlib.Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    with (out / 'station_training_readiness.csv').open('w', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=rows[0].keys())
        writer.writeheader()
        writer.writerows(rows)
    (out / 'training_readiness_summary.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(report, indent=2))

if __name__ == '__main__':
    main()
